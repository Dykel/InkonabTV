// Copies the web app (the same files GitHub Pages serves) into build/www for the Android app.
// The Google Play version gets its own config.js (android/app/src/play/assets/public/), which
// overrides the shared one: a pure player with no built-in server, free playlists or VPN.
import { cpSync, rmSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'build', 'www');
const files = ['index.html', 'config.js', 'manifest.webmanifest', 'icon.svg', 'logo1.svg', 'assets'];

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const f of files) cpSync(join(root, f), join(out, f), { recursive: true });
console.log('Web app copied to build/www');

const play = join(root, 'android', 'app', 'src', 'play', 'assets', 'public');
mkdirSync(play, { recursive: true });
// The built-in server and free playlist addresses are blanked out, not just overridden, so the
// Play package doesn't contain them at all.
const playConfig = readFileSync(join(root, 'config.js'), 'utf8')
  .replace(/^(\s*server:\s*)'[^']*'/m, "$1''")
  .replace(/^(\s*freePlaylists:\s*)\[[\s\S]*?\n\s*\]/m, '$1[]');
writeFileSync(join(play, 'config.js'), playConfig +
  "\n// Google Play version (generated by scripts/build-web.mjs).\nObject.assign(window.INKONAB_CONFIG, { playerMode: true, server: '', freePlaylists: [], vpn: false, updateUrl: '', autostart: false });\n");
console.log('Google Play config written to android/app/src/play/assets/public/config.js');

// InkonabTV+ (sideload "full" flavor) has MBC PLAY built in, read from the update site's tv.m3u
// (edit that file to change the channels); Settings → Extra playlists can hide it.
const full = join(root, 'android', 'app', 'src', 'full', 'assets', 'public');
mkdirSync(full, { recursive: true });
writeFileSync(join(full, 'config.js'), readFileSync(join(root, 'config.js'), 'utf8') +
  "\n// InkonabTV+ (generated by scripts/build-web.mjs).\nObject.assign(window.INKONAB_CONFIG, { downloaderCode: '3727335', freePlaylists: [\n  { name: 'MBC PLAY', url: 'https://inkonabtv.alwaysdata.net/tv.m3u' },\n] });\n");
console.log('InkonabTV+ config written to android/app/src/full/assets/public/config.js');

// InkonabTV Hotel ("hotel" flavor, tv.inkonab.app.hotel): its own welcome screen (hotel/web/) in
// place of the app's index.html: big channel tiles from the hotel playlist, Wi-Fi QR code and hotel
// information, no sign-in, films or series. Hotel details come from hotel/hotel.json (not in git: it
// holds the Wi-Fi password), or hotel/hotel.example.json.
const hotel = join(root, 'android', 'app', 'src', 'hotel', 'assets', 'public');
mkdirSync(hotel, { recursive: true });
for (const f of ['index.html', 'hotel.js', 'hotel.css']) cpSync(join(root, 'hotel', 'web', f), join(hotel, f));
let hotelFile = join(root, 'hotel', 'hotel.json');
try { readFileSync(hotelFile); } catch { hotelFile = join(root, 'hotel', 'hotel.example.json'); console.warn('hotel/hotel.json missing: using hotel.example.json'); }
const hotelCfg = JSON.parse(readFileSync(hotelFile, 'utf8'));
writeFileSync(join(hotel, 'config.js'), playConfig +
  "\n// InkonabTV Hotel (generated by scripts/build-web.mjs).\nObject.assign(window.INKONAB_CONFIG, { playerMode: true, server: '', freePlaylists: [], vpn: true, updateUrl: '', hotel: " +
  JSON.stringify(hotelCfg, null, 2) + " });\n");
console.log('Hotel screen written to android/app/src/hotel/assets/public/ (' + hotelCfg.name + ')');
